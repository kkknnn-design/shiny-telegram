"""Compile tools/album-notes/*.txt into album-assets/notes.js.

Source format, one block per album (title must match the catalog exactly):
    @ Album Title
    B background paragraph
    R listening notes paragraph
    K key track / key track / key track
Run from the repository root: python tools/build-album-notes.py
"""
import glob, json, re, sys
from pathlib import Path

sys.stdout.reconfigure(encoding='utf-8')
html = Path('album.html').read_text(encoding='utf-8')
albums = json.loads(re.search(r'const ALBUMS = (\[[\s\S]*?\n\]);', html).group(1))
by_title = {}
for a in albums:
    by_title.setdefault(a['t'], []).append(a)

notes, problems = {}, []
for path in sorted(glob.glob('tools/album-notes/*.txt')):
    title = None
    for raw in Path(path).read_text(encoding='utf-8').splitlines():
        line = raw.strip().replace('&amp;', '&')
        if not line:
            continue
        if line.startswith('@ '):
            title = line[2:].strip()
            if title not in by_title:
                problems.append(f'{path}: unknown title "{title}"'); title = None; continue
            if len(by_title[title]) > 1:
                problems.append(f'{path}: ambiguous title "{title}"')
            a = by_title[title][0]
            key = a['a'] + '|' + a['t']
            if key in notes:
                problems.append(f'{path}: duplicate notes for "{title}"')
            notes[key] = {}
        elif title and line[:2] in ('B ', 'R ', 'K '):
            a = by_title[title][0]
            entry = notes[a['a'] + '|' + a['t']]
            if line[0] == 'K':
                entry['k'] = [t.strip() for t in line[2:].split(' / ') if t.strip()]
            else:
                entry[line[0].lower()] = line[2:].strip()
        else:
            problems.append(f'{path}: stray line "{line[:40]}"')

for a in albums:
    entry = notes.get(a['a'] + '|' + a['t'])
    if not entry:
        problems.append(f'missing notes: {a["a"]} / {a["t"]}')
    elif not all(entry.get(f) for f in 'brk'):
        problems.append(f'incomplete notes: {a["a"]} / {a["t"]}')

if problems:
    print('\n'.join(problems)); sys.exit(1)
Path('album-assets/notes.js').write_text(
    '// Generated by tools/build-album-notes.py from tools/album-notes/*.txt — edit those, not this file.\n'
    'window.ALBUM_NOTES = ' + json.dumps(notes, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf-8')
chars = sum(len(n['b']) + len(n['r']) for n in notes.values())
print(f'Wrote notes for {len(notes)} albums, {chars} characters, average {chars // len(notes)} per album.')
